
package com.parabank.base;

import com.parabank.utils.TestData;

import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.openqa.selenium.By;
import org.openqa.selenium.WebDriver;
import org.openqa.selenium.WebElement;
import org.openqa.selenium.firefox.FirefoxDriver;
import org.openqa.selenium.support.ui.Select;
import org.openqa.selenium.support.ui.WebDriverWait;
import org.openqa.selenium.support.ui.ExpectedConditions;
import org.testng.Assert;
import org.testng.annotations.BeforeClass;
import org.testng.annotations.BeforeMethod;
import org.testng.annotations.AfterClass;

import java.time.Duration;

public class FindTransactionsBaseTest {

    protected WebDriver driver;
    protected String generatedTransactionId;

    private final String BASE_URL =
        "https://parabank.parasoft.com/parabank/index.htm";

    @BeforeClass
    public void setUp() {

        driver = new FirefoxDriver();
        driver.manage().window().maximize();

        WebDriverWait wait =
            new WebDriverWait(driver, Duration.ofSeconds(20));

        // Login
        driver.get(BASE_URL);

        wait.until(ExpectedConditions.visibilityOfElementLocated(
            By.name("username")
        )).sendKeys(TestData.VALID_USERNAME);

        driver.findElement(By.name("password"))
              .sendKeys(TestData.VALID_PASSWORD);

        driver.findElement(
            By.cssSelector("input.button[value='Log In']")
        ).click();

        wait.until(ExpectedConditions.elementToBeClickable(
            By.linkText("Bill Pay")
        ));

        System.out.println("Login successful.");

        createTestTransaction(wait);
    }

    private void createTestTransaction(WebDriverWait wait) {

        // Navigate using the application navigation link
        driver.findElement(By.linkText("Bill Pay")).click();

        // Wait until the actual bill payment form is visible
        wait.until(ExpectedConditions.visibilityOfElementLocated(
            By.name("payee.name")
        ));

        System.out.println("Bill Pay page opened.");

        // Fill payment details
        driver.findElement(By.name("payee.name"))
              .sendKeys("FindTxn Test Payee");

        driver.findElement(By.name("payee.address.street"))
              .sendKeys("123 Test Street");

        driver.findElement(By.name("payee.address.city"))
              .sendKeys("Chandigarh");

        driver.findElement(By.name("payee.address.state"))
              .sendKeys("Punjab");

        driver.findElement(By.name("payee.address.zipCode"))
              .sendKeys("160001");

        driver.findElement(By.name("payee.phoneNumber"))
              .sendKeys("9876543210");

        driver.findElement(By.name("payee.accountNumber"))
              .sendKeys("123456789");

        driver.findElement(By.name("verifyAccount"))
              .sendKeys("123456789");

        driver.findElement(By.name("amount"))
              .sendKeys("10");

        Select account = new Select(
            driver.findElement(By.name("fromAccountId"))
        );

        String accountId = account
            .getFirstSelectedOption()
            .getAttribute("value");

        driver.findElement(
            By.cssSelector("input.button[value='Send Payment']")
        ).click();

        wait.until(ExpectedConditions.visibilityOfElementLocated(
            By.id("billpayResult")
        ));

        String result = driver.findElement(By.tagName("body"))
                              .getText();

        System.out.println("Payment result:");
        System.out.println(result);

        Assert.assertTrue(
            result.contains("Bill Payment Complete"),
            "Could not create transaction for Find Transactions."
        );

        // Open the activity page for the funding account
        driver.get(
            "https://parabank.parasoft.com/parabank/activity.htm?id="
            + accountId
        );

        wait.until(ExpectedConditions.visibilityOfElementLocated(
            By.id("transactionTable")
        ));

        // Find the transaction generated by this payment
        List<WebElement> links = driver.findElements(
            By.cssSelector(
                "#transactionTable a[href*='transaction.htm']"
            )
        );

        for (WebElement link : links) {

            WebElement row = link.findElement(
                By.xpath("./ancestor::tr")
            );

            if (row.getText().contains("FindTxn Test Payee")) {

                String href = link.getAttribute("href");

                Matcher matcher = Pattern
                    .compile("[?&]id=(\\d+)")
                    .matcher(href);

                if (matcher.find()) {
                    generatedTransactionId = matcher.group(1);
                    break;
                }
            }
        }

        Assert.assertNotNull(
            generatedTransactionId,
            "Could not extract the generated transaction ID."
        );

        System.out.println(
            "Generated transaction ID: " + generatedTransactionId
        );
    }

    @BeforeMethod
    public void openFindTransactionsPage() {

        driver.get(
            "https://parabank.parasoft.com/parabank/findtrans.htm"
        );

        new WebDriverWait(driver, Duration.ofSeconds(20))
            .until(ExpectedConditions.visibilityOfElementLocated(
                By.id("transactionId")
            ));
    }

    @AfterClass
    public void tearDown() {

        if (driver != null) {
            driver.quit();
            System.out.println("Find Transactions module completed.");
        }
    }
}
